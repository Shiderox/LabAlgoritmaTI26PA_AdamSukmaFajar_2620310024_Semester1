#include <iostream>
using std::cout;
using std::endl;

int main ()
{
    int a = 11;
    int b = 5;

    cout << "a = 11" << endl << "b = 5\n" << endl;
    cout << "a + b is : " << a+b << endl;
    cout << "a - b is : " << a-b << endl;
    cout << "a * b is : " << a*b << endl;
    cout << "a : b is : " << a/b << endl;
    cout << "a % b is : " << a%b<< endl;
    cout << "a++ is : " << a++ << endl;
    cout << "a-- is : " << a-- << endl;
    return 0;
    
}